// Usage:
//   npm run check:assets   -> verifies images, prints a report, exits 1 only for BROKEN references
//   npm run images:sync    -> same, and also rewrites
//                              src/app/core/constants/pending-images.ts   (which photos are still missing)
//                              PRODUCT_IMAGE_VERIFICATION.md              (per-product report)
// Run `npm run images:sync` after adding or replacing photos in public/images/products/<category>/.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const write = process.argv.includes('--write');
const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
let errors = 0;
const fail = (m) => { console.error('✗', m); errors++; };

/** width/height of a PNG or JPEG (null if the file is not a valid image). */
function dimensions(buf) {
  if (buf.length > 24 && buf.subarray(1, 4).toString() === 'PNG') return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length) {
      if (buf[i] !== 0xff) { i++; continue; }
      const m = buf[i + 1];
      if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
      i += 2 + buf.readUInt16BE(i + 2);
    }
  }
  return null;
}
const fileState = (ref) => {
  const file = join(root, 'public', ref);
  const dir = dirname(file);
  const exists = existsSync(dir) && readdirSync(dir).includes(ref.split('/').pop()); // exact-case check
  if (!exists) return { exists: false };
  const dim = dimensions(readFileSync(file));
  return { exists: true, dim, valid: !!dim };
};

// 1. every /images/... path written in src/ (except the product map, handled below)
const sources = walk(join(root, 'src')).filter((f) => /\.(ts|html|css)$/.test(f) && !f.endsWith('.spec.ts'));
const refs = new Set();
for (const f of sources) for (const m of readFileSync(f, 'utf8').matchAll(/['"(](\/images\/[^'")\s]+)/g)) refs.add(m[1]);
for (const ref of [...refs].sort()) {
  if (ref.startsWith('/images/products/')) continue;
  const s = fileState(ref);
  if (!s.exists) fail(`missing file (check name and case): public${ref}`);
  else if (['.png', '.jpg', '.jpeg'].includes(extname(ref)) && !s.valid) fail(`not a valid image: public${ref}`);
}

// 2. products -> pictures
const assets = readFileSync(join(root, 'src/app/core/constants/image-assets.ts'), 'utf8');
const pathOfKey = Object.fromEntries([...assets.matchAll(/(\w+): '(\/images\/products\/[^']+)'/g)].map((m) => [m[1], m[2]]));
const catalogDir = join(root, 'src/app/features/home/data/catalog');
const products = [];
for (const f of readdirSync(catalogDir).filter((n) => n.endsWith('.ts') && !n.endsWith('.spec.ts') && n !== 'index.ts')) {
  for (const line of readFileSync(join(catalogDir, f), 'utf8').split('\n')) {
    const m = line.match(/id: '([^']+)', category: '([^']+)',(?: brand: (?:'[^']*'|"[^"]*"),)? name: '([^']*)'.*?image: I\.(\w+)/);
    if (m) products.push({ id: m[1], category: m[2], name: m[3], key: m[4], path: pathOfKey[m[4]] });
  }
}
const idSeen = new Set(), pathUse = {};
const rows = products.map((p) => {
  if (!p.path) fail(`${p.id}: image key "${p.key}" is not defined in image-assets.ts`);
  if (idSeen.has(p.id)) fail(`duplicate product id ${p.id}`); idSeen.add(p.id);
  pathUse[p.path] = (pathUse[p.path] ?? 0) + 1;
  const s = p.path ? fileState(p.path) : { exists: false };
  if (s.exists && !s.valid) fail(`${p.id}: file is not a valid PNG/JPEG: public${p.path}`);
  return { ...p, ...s };
});
for (const [p, n] of Object.entries(pathUse)) if (n > 1) fail(`picture used by ${n} products: ${p}`);

const ready = rows.filter((r) => r.exists && r.valid);
const pending = rows.filter((r) => !r.exists);
console.log(`${rows.length} products | ${ready.length} photos present | ${pending.length} photos pending`);
for (const r of pending) console.log(`  PENDING  public${r.path}   (${r.name})`);

if (write) {
  writeFileSync(join(root, 'src/app/core/constants/pending-images.ts'),
`// GENERATED by \`npm run images:sync\` – do not edit by hand.
// Photo files that do not exist yet. Their product cards show the "Photo coming soon" picture.
export const PENDING_IMAGES: ReadonlySet<string> = new Set<string>([
${pending.map((r) => `  '${r.path}',`).join('\n')}
]);
`);
  const rel = (r) => (r.exists && r.valid ? `Photograph – ${r.dim[0]}×${r.dim[1]}px` : 'PENDING – photograph required');
  let md = `# Product image verification\n\nGenerated by \`npm run images:sync\`. Only real photographs count as ready; no drawings, vectors or illustrations are used for products.\n\n`;
  md += `| Total products | Photos present | Photos pending |\n|---|---|---|\n| ${rows.length} | ${ready.length} | ${pending.length} |\n\n`;
  md += `## All products\n\n| # | Product | Category | Image file | Local path | File exists | Image status |\n|---|---|---|---|---|---|---|\n`;
  rows.forEach((r, i) => { md += `| ${i + 1} | ${r.name} | ${r.category} | ${r.path.split('/').pop()} | \`${r.path}\` | ${r.exists ? 'Yes' : 'No'} | ${rel(r)} |\n`; });
  md += `\n## Pending photographs (add these files)\n\nSave a studio-style photo (white or light-grey background, product centred, at least 800×800px) at each path, then run \`npm run images:sync\`.\n\n`;
  md += pending.length ? pending.map((r) => `- [ ] \`public${r.path}\` – ${r.name} (${r.category})`).join('\n') + '\n' : 'None – every product has a photograph.\n';
  const bc = join(root, 'scripts/browser-check.md');
  if (existsSync(bc)) md += `\n${readFileSync(bc, 'utf8')}\n`;
  writeFileSync(join(root, 'PRODUCT_IMAGE_VERIFICATION.md'), md);
  console.log('Wrote pending-images.ts and PRODUCT_IMAGE_VERIFICATION.md');
}
if (errors) { console.error(`${errors} problem(s) found.`); process.exit(1); }
console.log('✓ No broken image references.');
